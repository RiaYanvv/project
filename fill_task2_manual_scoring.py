def main() -> None:
    wb = load_workbook(SRC)
    it = wb["Item Scoring"]
    hdr = {str(c.value): c.column for c in it[1]}
    diffs = 0
    for row in it.iter_rows(min_row=2):
        qid = str(row[hdr["Question ID"] - 1].value).strip()
        rank = int(row[hdr["Rank"] - 1].value)
        rel, note = ITEMS[qid][rank - 1]
        lvl = str(row[hdr["Authority (S/A+/A/B+)"] - 1].value or "").strip()
        auto = row[hdr["Auto Relevance (0-2)"] - 1].value
        if auto is not None and int(auto) != rel:
            note += f" ｜ 人工判定与Auto({auto})不同，请复核"
            diffs += 1
        row[hdr["Relevance (0/1/2)"] - 1].value = rel
        row[hdr["Authority (0/1/2)"] - 1].value = AUTH.get(lvl, "")
        row[hdr["Notes"] - 1].value = note

    qs = wb["Question Scoring"]
    qh = {str(c.value): c.column for c in qs[1]}
    for row in qs.iter_rows(min_row=2):
        qid = str(row[qh["Question ID"] - 1].value).strip()
        cov, note = COV[qid]
        row[qh["Coverage (0/1/2)"] - 1].value = cov
        row[qh["Notes"] - 1].value = note

    sm = wb["Summary"]
    sm.append([])
    sm.append(["Scoring pass", "AI-assisted pre-scoring (content-based). Review flagged rows before finalising.", None, None])
    sm.cell(row=sm.max_row, column=1).font = Font(bold=True)

    wb.save(SRC)
    shutil.copy2(SRC, DL)

    # Deterministic authority average, read back from the sheet we just wrote.
    chk = load_workbook(SRC)["Item Scoring"]
    ah = {str(c.value): c.column for c in chk[1]}
    scored = [r[ah["Authority (0/1/2)"] - 1].value for r in chk.iter_rows(min_row=2)
              if r[ah["Question ID"] - 1].value]
    scored = [v for v in scored if v not in (None, "")]
    globals()["AVG_AUTHORITY"] = sum(scored) / len(scored) if scored else 0.0

    vals = [sum(r for r, _ in ITEMS[q]) / 5 for q in ITEMS]
    print(f"saved {SRC} and {DL}")
    print(f"rows flagged as 人工≠Auto: {diffs}")
    print(f"Avg Relevance = {sum(vals)/len(vals):.3f}   "
          f"Avg Authority = {AVG_AUTHORITY:.3f}   "
          f"Avg Coverage = {sum(c for c, _ in COV.values())/len(COV):.3f}")


if __name__ == "__main__":
    main()
